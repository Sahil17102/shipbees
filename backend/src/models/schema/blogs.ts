import { boolean, integer, pgTable, text, timestamp, varchar } from 'drizzle-orm/pg-core'

export const blogs = pgTable('blogs', {
  id: integer('id').primaryKey().generatedByDefaultAsIdentity(),
  title: varchar('title', { length: 512 }).notNull(),
  slug: varchar('slug', { length: 512 }).notNull().unique(),
  excerpt: text('excerpt'),
  content: text('content').notNull(),
  featured_image: varchar('featured_image', { length: 1024 }),
  featured_image_alt: varchar('featured_image_alt', { length: 512 }),
  tags: text('tags'),
  meta_title: varchar('meta_title', { length: 512 }),
  meta_description: text('meta_description'),
  focus_keywords: varchar('focus_keywords', { length: 512 }),
  og_image: varchar('og_image', { length: 1024 }),
  published_at: timestamp('published_at'),
  author_id: integer('author_id'),
  is_featured: boolean('is_featured').notNull().default(false),
  views: integer('views').notNull().default(0),
  comments_count: integer('comments_count').notNull().default(0),
  category: varchar('category', { length: 120 }).notNull().default('Shipping Tips'),
  status: varchar('status', { length: 24 }).notNull().default('draft'),
  author_name: varchar('author_name', { length: 160 }).notNull().default('Shipray'),
  author_role: varchar('author_role', { length: 160 }).notNull().default('Shipray Editorial Team'),
  read_time_minutes: integer('read_time_minutes').notNull().default(1),
  accent_color: varchar('accent_color', { length: 16 }).notNull().default('#6C4DFF'),
  created_at: timestamp('created_at').defaultNow().notNull(),
  updated_at: timestamp('updated_at').defaultNow().notNull(),
})
