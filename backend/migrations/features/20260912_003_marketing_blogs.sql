create table if not exists blogs (
  id integer generated by default as identity primary key,
  title varchar(512) not null,
  slug varchar(512) not null unique,
  excerpt text,
  content text not null,
  featured_image varchar(1024),
  featured_image_alt varchar(512),
  tags text,
  meta_title varchar(512),
  meta_description text,
  focus_keywords varchar(512),
  og_image varchar(1024),
  published_at timestamp,
  author_id integer,
  is_featured boolean not null default false,
  views integer not null default 0,
  comments_count integer not null default 0,
  created_at timestamp not null default now(),
  updated_at timestamp not null default now()
);

do $$
begin
  if exists (
    select 1 from information_schema.columns
    where table_schema = current_schema() and table_name = 'blogs'
      and column_name = 'id' and is_identity = 'NO' and column_default is null
  ) then
    alter table blogs alter column id add generated by default as identity;
  end if;
end $$;

do $$
declare
  sequence_name text;
begin
  sequence_name := pg_get_serial_sequence('blogs', 'id');
  if sequence_name is not null then
    execute format(
      'select setval(%L, coalesce((select max(id) from blogs), 0) + 1, false)',
      sequence_name
    );
  end if;
end $$;

alter table blogs
  add column if not exists category varchar(120) not null default 'Shipping Tips',
  add column if not exists status varchar(24) not null default 'draft',
  add column if not exists author_name varchar(160) not null default 'Shipray',
  add column if not exists author_role varchar(160) not null default 'Shipray Editorial Team',
  add column if not exists read_time_minutes integer not null default 1,
  add column if not exists accent_color varchar(16) not null default '#6C4DFF';

update blogs set status = case
  when published_at is not null and published_at <= now() then 'published'
  when published_at is not null and published_at > now() then 'scheduled'
  else 'draft'
end;

update blogs set read_time_minutes = greatest(1, ceil(
  array_length(regexp_split_to_array(trim(regexp_replace(content, '<[^>]+>', ' ', 'g')), '\s+'), 1) / 220.0
)::integer)
;

alter table blogs drop constraint if exists blogs_status_check;
alter table blogs add constraint blogs_status_check
  check (status in ('draft', 'published', 'scheduled', 'archived'));

create index if not exists blogs_publication_idx on blogs (status, published_at desc);
create index if not exists blogs_category_idx on blogs (category, published_at desc);
create index if not exists blogs_featured_idx on blogs (is_featured, published_at desc);
